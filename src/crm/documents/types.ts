import type { ApiResponse } from "../../core/http-client.js";
import type { RequestConfig } from "../../core/resource.js";

declare const uuidBrand: unique symbol;
declare const versionBrand: unique symbol;
declare const dateBrand: unique symbol;
declare const timestampBrand: unique symbol;
declare const decimalBrand: unique symbol;

/** Native owners can retain older UUIDs; CRM entity identities are UUIDv7. */
export type NativeDocumentId = string & { readonly [uuidBrand]: "native" | "v7" };
export type CrmDocumentId = NativeDocumentId & { readonly [uuidBrand]: "v7" };
export type CrmDocumentVersion = number & { readonly [versionBrand]: true };
export type CrmDocumentDate = string & { readonly [dateBrand]: true };
export type CrmDocumentTimestamp = string & { readonly [timestampBrand]: true };
export type CrmDocumentDecimal<Scale extends 2 | 4 = 2> = string & { readonly [decimalBrand]: Scale };
export type CrmNativeDocumentType = "quote" | "invoice" | "contract" | "recurring_schedule";
export type CrmDocumentResponse<T> = ApiResponse<T>;
export type CrmDocumentWriteOperation = "upload" | "replaceVersion" | "share" | "revokeShare" | "archive" | "createQuote" | "link" | "unlink";
export interface CrmDocumentWriteConfig extends Omit<RequestConfig, "maxRetries" | "idempotencyKey"> {
  /** Persist this key and the original payload before sending. Never generated by this adapter. */
  idempotencyKey: string;
}
export type CrmDocumentRecoveryConfig = Pick<RequestConfig, "timeout" | "signal">;

